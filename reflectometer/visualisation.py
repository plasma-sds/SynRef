def plot_cwt(data, filename = False, show = False, text = None, 
             frequency_index = 0, figsize=None,
             event = None, signal = None, gauss_fit = False):
    """
    Plot the Continuous Wavelet Transform as an image plot.

    Parameters
    ----------
    data : dict
        Dictionary with keys:
        - "frequencies": array-like, frequency values in Hz
        - "time": array-like, time values in seconds
        - "phase_field": 2D array of phase values
    filename : str, optional
        If provided, the figure will be saved to this file. 
        Extension has to be included!!!
    show : bool, default False
        Whether to display the figure interactively.
    text : str, optional
        Text to overlay on the plot. Generated by ref_data(...)
    figsize : tuple, default (8, 5)
        Figure size in inches.

    Returns
    -------
    fig, ax : matplotlib.figure.Figure, matplotlib.axes.Axes
        Figure and axes objects of the plot.
    """
    f = frequency_index
    freq = data["frequencies"][data["frequency_indices"][f]]
    tu = 1e-6 # unit of time (microseconds)
    cwt = data["cwt_matrix"][f, :, :]
    gauss = data["gauss_fit"][f, :, :]
    t = data["time"]/tu
    T = data["period"]/tu
    
    
    if(signal is not None):
        # --- Define figure ---
        if figsize is None: figsize = (9,6)
        fig = plt.figure(figsize=figsize, dpi=100)
        
        # --- Define the grid for the subplots --- 
        gs = gridspec.GridSpec( 2, 2, width_ratios=[20, 0.5], 
                height_ratios=[0.8, 3], hspace=0.1, wspace=0.3)

        # --- Subplots ---
        axs = [fig.add_subplot(gs[0, 0])]
        axs.append(fig.add_subplot(gs[1, 0], sharex=axs[0]))
        cax = fig.add_subplot(gs[1, 1])  # colorbar axis
        
        # --- Complex signal - time series ---
        axs[0].plot(t, signal[:, f].imag, color='tab:orange')
        axs[0].plot(t, signal[:, f].real, color='tab:blue')
        
        # --- Time-frequency field | cwt transform ---
        im = axs[1].imshow(np.abs(cwt), extent = [t[0], t[-1], T[-1], T[0]], 
                            aspect='auto', cmap='jet')
        # t - time series, T - wavelet waveperiod (freq on twin axis)
        
        # --- Set the ax parameters ---
        title = (f"Complex signal and its Continuous Wavelet Transform" +
                 f" | {freq:.1f} GHz")
        axs[0].set_title(title, fontweight='bold')
        axs[0].set_ylabel("Signal")
        axs[0].grid(True, alpha=0.3)
        axs[0].tick_params(axis='x', which='both', bottom=0, labelbottom=0)
        axs[0].legend([r"$\Re$", r"$\Im$"], loc = 'lower left')
        axs[1].set_ylabel("Wave period Ts [\u00B5s]")
        axs[1].set_xlabel("Time t [\u00B5s]")
        axs[1].grid(True, alpha=0.3)
        
        # --- Twin axis for frequency of the sampling wavelet ---
        axs_twin = axs[1].twinx()
        axs_twin.set_ylim(axs[1].get_ylim())  # align scales
        yticks = axs[1].get_yticks()[1:-1]
        axs_twin.set_yticks(yticks)
        axs_twin.set_yticklabels([f"{1/f:.3f}" for f in yticks])
        axs_twin.set_ylabel("Frequency fs [MHz]")
        
        # --- Colorbar ---
        cb = plt.colorbar(im, cax=cax)
        cb.ax.ticklabel_format(style='sci', scilimits=(0, 0))
        cb.set_label("CWT Coefficient")
        
        # --- Event localisation ---
        if (event is not None):
            # scatter: maximum of wavelet transform (gauss fit)
            # event start/end: FWHM along the x axis (gauss fit)
            (i1,i2) = event["FWHM_inds"][f, :]
            
            axs[1].scatter(event["x0"][f]/tu, event["y0"][f]/tu,
                           color = "black")
            axs[1].plot([t[i1], t[i1]], [T[0], T[-1]])
            axs[1].plot([t[i2], t[i2]], [T[0], T[-1]])
        
        # Extra infromation in textbox
        if (text is not None):
            props = dict(boxstyle='round', facecolor='grey', alpha=0.7)
            axs[1].text(0.05, 0.95, text, transform=axs[1].transAxes,
                        fontsize=10, verticalalignment='top', bbox=props)
            
    
    elif (gauss_fit):
        vmin = min(np.abs(cwt).min(), np.abs(gauss).min())
        vmax = max(np.abs(cwt).max(), np.abs(gauss).max())
        
        # --- Define figure ---
        if figsize is None: figsize = (8,7)
        fig = plt.figure(figsize=figsize, dpi=100)
        
        # --- Define the grid for the subplots --- 
        gs = gridspec.GridSpec(2, 2, width_ratios=[20, 0.8],
            height_ratios=[1, 1], hspace=0.2, wspace=0.3)
        
        # --- Subplots ---
        axs = [fig.add_subplot(gs[0, 0])]
        axs.append(fig.add_subplot(gs[1, 0], sharex=axs[0], sharey=axs[0]))
        cax = fig.add_subplot(gs[:, 1])  # colorbar spans both rows
        
        # --- Continuous Wavelet Transform ---
        im = axs[0].imshow(np.abs(cwt), extent = [t[0], t[-1], T[-1], T[0]], 
                           aspect='auto', cmap='jet', vmin=vmin, vmax=vmax)
        # t - time series, T - wavelet waveperiod (freq on twin axis)
        
        # --- Fitted asymmetric Gauss ---
        im = axs[1].imshow(np.abs(gauss), extent = [t[0], t[-1], T[-1], T[0]], 
                           aspect='auto', cmap='jet', vmin=vmin, vmax=vmax)
        # t - time series, T - wavelet waveperiod (freq on twin axis)
        
        # --- Set the ax parameters ---
        axs[0].grid(True, alpha=0.3)
        title = f"Continuous Wavelet Transform | {freq:.1f} GHz"
        axs[0].set_title(title, fontweight = 'bold')
        axs[0].set_ylabel("Wave period Ts [\u00B5s]")
        axs[0].tick_params(axis='x', which='both', bottom=0, labelbottom=0)
        axs[1].grid(True, alpha=0.3)
