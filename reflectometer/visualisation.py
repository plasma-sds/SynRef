def plot_density(data, filename = False, frame = 0, show = False, 
                 reflectometer = None, text = None, figsize=(5, 5*1.5)):
    """
    Plot a 2D density field with optional reflectometer information overlay.

    Parameters
    ----------
    data : dict
        Dictionary containing the density data with keys:
        - "X", "Y": coordinate arrays in meters
        - "t": array of time points in seconds
        - "Z": 3D array of density values (time, Y, X)
    filename : str, optional
        If provided, the figure is saved to this file.
        Extension has to be included!!!
    frame : int, default 0
        Time frame index to plot.
    show : bool, default False
        Whether to display the figure interactively.
    reflectometer : object, optional
        Reflectometer object with attributes:
        - setup_map: dict with "x_abs", "y_abs" (not necessary)
        - antenna_pos: antenna position
        - angle: angle in degrees
    text : str, optional
        Text to overlay on the plot.
    figsize : tuple, default (5, 7.5)
        Figure size.

    Returns
    -------
    fig, ax : matplotlib.figure.Figure, matplotlib.axes.Axes
        Figure and axes objects.
    """
    
    # setting the axis and field data
    ref = reflectometer
    if(ref != None and hasattr(ref, "setup_map")):
        X, Y = ref.setup_map["x_abs"]*1e3, ref.setup_map["y_abs"]*1e3
    else: 
        X, Y = data["X"]*1e3, data["Y"]*1e3
    t, Z = data["t"][frame]*1e6, data["Z"][frame]
    min_val = np.min(Z)
    max_val = np.max(Z)
    
    # Setting the plot data:
    levels = 40
    cmap = "viridis"
    
    # Set up figure layout and color map
    fig, (ax, cax1) = plt.subplots(figsize=figsize, ncols=2,
                                   gridspec_kw={"width_ratios":[10, 0.5]},
                                   constrained_layout=True)
    # fig.subplots_adjust(left=0.15, right=0.95, top=0.95, bottom=0.08)
    contour = ax.contourf(X, Y, Z, levels=levels, cmap=cmap,
                          vmin=min_val, vmax=max_val)
    
    # Create the colorbar
    cbar = plt.colorbar(contour, cax=cax1)
    cax2 = cax1.twinx()
    cax2.set_ylim([func.get_plasma_frequency(min_val) * 1e-9, 
                   func.get_plasma_frequency(max_val) * 1e-9])
    cax2.set_ylabel(r'Density [m$^{-3}$] Frequency [GHz]')
    
    # If a reflectometer is defined, its path is displayed:
    if(ref != None):
        pos, dist = ref.antenna_pos * 1e3 + Y[0], (X[-1] - X[0]) * 0.8
        xs = (X[0], X[0] + dist)
        ys = (pos, np.tan(ref.angle / 180 * np.pi) * abs(dist) + pos)
        ax.plot(xs, ys, c = "black", linestyle= "--")
    
    # Create the appropriate annotations
    ax.set_title("Density field", loc = "center")
    ax.set_xlabel("Radial position x [mm]")
    ax.set_ylabel("Poloidal position y [mm]")
    ax.set_title(f"{round(t,1)} [\u00B5s]", loc = "right")
    
    if (text != None):
        props = dict(boxstyle='round', facecolor='grey', alpha=0.5)
        ax.text(0.05, 0.95, text, transform=ax.transAxes, fontsize=10,
            verticalalignment='top', bbox=props)
    
    if (show == False): plt.close()
    if (filename != False): 
        fig.savefig(filename, dpi=300)
    
    return fig, ax

